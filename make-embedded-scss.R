# Writes _extensions/sts/embedded.scss, which embeds binary assets as base64
# data URIs:
#   - @font-face rules for IBM Plex Sans, from the woff2 files in fonts/
#   - $sts-lockup-white, the white horizontal lockup used on the title slide
#
# Quarto does not rewrite url() paths in an extension theme, so a relative
# url("fonts/...") resolves against the compiled CSS in <deck>_files/ and
# fails. Data URIs remove the path entirely and work offline.
#
# Run from the repository root after replacing a font or logo file:
#   Rscript make-embedded-scss.R

ext_dir  <- "_extensions/sts"
out_file <- file.path(ext_dir, "embedded.scss")

encode <- function(path) {
  bytes <- readBin(path, "raw", n = file.size(path))
  base64enc::base64encode(bytes)
}

faces <- data.frame(
  file   = c(
    "IBMPlexSans-Regular.woff2",
    "IBMPlexSans-Italic.woff2",
    "IBMPlexSans-Medium.woff2",
    "IBMPlexSans-SemiBold.woff2"
  ),
  style  = c("normal", "italic", "normal", "normal"),
  weight = c(400, 400, 500, 600)
)

face_rule <- function(file, style, weight) {
  paste0(
    "@font-face {\n",
    "  font-family: \"IBM Plex Sans\";\n",
    "  font-style: ", style, ";\n",
    "  font-weight: ", weight, ";\n",
    "  font-display: swap;\n",
    "  src: url(\"data:font/woff2;base64,",
    encode(file.path(ext_dir, "fonts", file)),
    "\") format(\"woff2\");\n",
    "}\n"
  )
}

font_rules <- mapply(
  face_rule,
  faces$file,
  faces$style,
  faces$weight
)

lockup_white <- paste0(
  "$sts-lockup-white: url(\"data:image/svg+xml;base64,",
  encode(file.path(ext_dir, "lockup-horiz-white.svg")),
  "\");"
)

writeLines(
  c(
    "/*-- scss:defaults --*/",
    "",
    "// Generated by make-embedded-scss.R; do not edit by hand.",
    "",
    "// lockup-horiz-white.svg, copied from sea-through-science/logo/svg/",
    lockup_white,
    "",
    "/*-- scss:rules --*/",
    "",
    "// IBM Plex Sans, IBM/plex release @ibm/plex-sans@1.1.0,",
    "// SIL Open Font License 1.1 (fonts/OFL.txt).",
    font_rules
  ),
  out_file
)
